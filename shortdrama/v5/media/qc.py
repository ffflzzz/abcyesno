def text_rule(on_screen_text: str) -> str:
    """按 brief 的 `on_screen_text` 取第 1 条判据（默认 allow）。"""
    return TEXT_RULE_FORBID if str(on_screen_text).strip().lower() == "forbid" \
        else TEXT_RULE_ALLOW


#: 模块级默认政策 —— 由 `pipeline` 在每轮媒体链开工前按 brief 设置**一次**。
