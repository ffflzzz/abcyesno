_DEFAULT_TEXT_POLICY = "allow"


def set_text_policy(on_screen_text: str) -> None:
    """设置本轮媒体链的「画面内文字」政策（pipeline 开工前调一次）。"""
    global _DEFAULT_TEXT_POLICY
    _DEFAULT_TEXT_POLICY = (
        "forbid" if str(on_screen_text).strip().lower() == "forbid" else "allow")


def current_text_policy() -> str:
    """当前生效的「画面内文字」政策（诊断/日志用）。"""
    return _DEFAULT_TEXT_POLICY


