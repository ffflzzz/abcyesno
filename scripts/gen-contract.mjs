// gen-contract.mjs — build-time contract codegen.
//
// Scans the LangGraph agent manifests shipped beside each agent package under
// hermes-fork/skills/langgraph_agents/agents/*/manifest.json and generates the
// frontend's bundled contract data (manifests + whitelist + launcher apps).
//
// This is the "编译面板": adding a LangGraph agent = drop a manifest.json next
// to its agent.py (with hidden:false and optional ui/launcher metadata) and
// rebuild. No frontend source edits, no hand-maintained whitelist/launcher.
//
// Run directly (`node scripts/gen-contract.mjs`) or automatically via the
// `contract-codegen` Vite plugin on every build/dev start.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const AGENTS_DIR = path.join(REPO_ROOT, "hermes-fork", "skills", "langgraph_agents", "agents");
const OUT_FILE = path.join(REPO_ROOT, "src", "contract", "manifests.generated.js");

// Optional per-agent search dirs (mirrors agui-server.js resolveAgentsDirs) so
// a user-installed agent directory can contribute too.
function agentDirs() {
  const dirs = [AGENTS_DIR];
  const extra = process.env.ABC_LANGGRAPH_AGENTS_DIR;
  if (extra) dirs.push(extra);
  return dirs.filter(Boolean);
}

function scanManifests() {
  const manifests = [];
  for (const dir of agentDirs()) {
    let entries = [];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const ent of entries) {
      if (!ent.isDirectory()) continue;
      const mf = path.join(dir, ent.name, "manifest.json");
      if (!fs.existsSync(mf)) continue;
      try {
        const data = JSON.parse(fs.readFileSync(mf, "utf8"));
        // Exclude hidden agents (test/demo/legacy). Production exposure is a
        // data decision (hidden flag), not a frontend code decision.
        if (data && data.id && !data.hidden) manifests.push(data);
      } catch (e) {
        console.warn(`[gen-contract] skip ${ent.name}: ${e.message}`);
      }
    }
  }
  manifests.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return manifests;
}

function buildLauncherApps(manifests) {
  const apps = [];
  for (const m of manifests) {
    if (!m.launcher) continue;
    // openMode is data-driven (manifest field `launcher.openMode`).
    //   "newTab" → open the workbench in a fresh in-app tab (漫剧go default).
    //   anything else (incl. omitted) → "tab": replace the current Launcher
    //   tab in-place. (The old "window" standalone-window mode was removed;
    //   ides are always in-app now.)
    const openMode = m.launcher.openMode === "newTab" ? "newTab" : "tab";
    apps.push({
      key: m.id,
      title: m.launcher.title || m.name,
      icon: m.launcher.icon || m.icon || "film",
      iconSrc: m.launcher.iconSrc || undefined,
      color: m.launcher.color || "#111827",
      workflowId: m.id,
      openMode,
    });
  }
  return apps;
}

function generate() {
  const manifests = scanManifests();
  const allowedIds = manifests.map((m) => m.id);
  const launcherApps = buildLauncherApps(manifests);

  const body = `// AUTO-GENERATED by scripts/gen-contract.mjs — DO NOT EDIT BY HAND.
// Source of truth: hermes-fork/skills/langgraph_agents/agents/*/manifest.json
// (agents marked "hidden": true are excluded). To add a workflow, drop a
// manifest.json beside its agent.py and rebuild — no frontend code changes.
const manifests = ${JSON.stringify(manifests, null, 2)};

const allowedIds = ${JSON.stringify(allowedIds)};

const launcherApps = ${JSON.stringify(launcherApps, null, 2)};

export { manifests, allowedIds, launcherApps };
`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body, "utf8");
  console.log(
    `[gen-contract] wrote ${path.relative(REPO_ROOT, OUT_FILE)} — ` +
      `${manifests.length} manifest(s), ${launcherApps.length} launcher app(s)`
  );
  return { manifests, allowedIds, launcherApps };
}

// Allow `node scripts/gen-contract.mjs` to run directly.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generate();
}

export { generate };
